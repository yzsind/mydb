#!/usr/bin/env python3
"""Generate public error and startup-option references from Rust registries."""

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generated():
    source = (ROOT / "src/error/catalog.rs").read_text()
    definitions = re.findall(
        r'pub const (\w+): ErrorSpec =\s*ErrorSpec::new\(\s*ErrorDomain::MyDb,\s*(\d+),\s*\*b"([A-Z0-9]{5})",\s*"([A-Z0-9_]+)"\s*,?\s*\);',
        source,
    )
    registry = source.split("pub const MYDB_ERROR_SPECS:", 1)[1].split("];", 1)[0]
    names = set(re.findall(r"^\s+(\w+),", registry, re.MULTILINE))
    entries = sorted(
        (int(code), symbol, state)
        for name, code, state, symbol in definitions
        if name in names
    )
    assert len(entries) == len(names), "Unparsed extension error definition"
    assert len({e[0] for e in entries}) == len(entries), "Duplicate extension errno"
    table = "| errno | symbol | SQLSTATE |\n| ---: | --- | --- |\n"
    table += "".join(
        f"| {code} | `{symbol}` | `{state}` |\n" for code, symbol, state in entries
    )
    path = ROOT / "docs/error-codes.md"
    text = path.read_text()
    text = re.sub(
        r"(?<=<!-- BEGIN GENERATED MYDB ERRORS -->\n).*?(?=<!-- END GENERATED MYDB ERRORS -->)",
        table,
        text,
        flags=re.DOTALL,
    )
    yield path, text
    source = (
        (ROOT / "src/startup_config.rs")
        .read_text()
        .split("static OPTION_SPECS:", 1)[1]
        .split("\n];", 1)[0]
    )
    entries = []
    for block in re.findall(r"OptionSpec \{(.*?)\n    \}", source, re.DOTALL):
        name = re.search(r'name: "([^"]+)"', block)[1]
        env = re.search(r'env: "([^"]+)"', block)[1]
        kind = re.search(r"kind: (.*?),\n\s*(?:aliases|cli):", block, re.DOTALL)[1]
        aliases = ", ".join(
            re.findall(r'"([^"]+)"', block.split("aliases:", 1)[1].split("cli:", 1)[0])
        )
        entries.append(
            (
                name,
                env,
                kind,
                aliases,
                "true" in block.split("cli:", 1)[1].split(",", 1)[0],
            )
        )
    for name, env, kind in re.findall(
        r'spec!\(\s*"([^"]+)",\s*"([^"]+)",\s*(.*?)\s*\),\n', source, re.DOTALL
    ):
        entries.append((name, env, kind, "", False))
    assert len(entries) == source.count("OptionSpec {") + source.count("spec!("), (
        "Unparsed startup option"
    )
    text = """<!-- Automatically generated by scripts/generate_public_references.py; do not edit. -->
# Startup Option Registry

This table follows the explicit option-file registry in this source checkout.
Registered writable GLOBAL system variables are an additional surface; inspect
`SHOW GLOBAL VARIABLES` and the [scope and persistence rules](configuration.md#system-variable-scope-and-persistence-protection).
Aliases apply to option files. CLI availability below follows the registry; use
`mydb --help` for CLI spelling and argument conventions.

All entries configure startup. A matching SQL variable may also support dynamic
SET; a startup entry alone does not establish that capability. Defaults, coupled
constraints and effects are described in [configuration](configuration.md),
[resource settings](configuration-resources.md), [operations settings](configuration-operations.md)
and [service settings](configuration-services.md). Defaults can be derived from
hardware, so this registry does not invent a constant default.

`Bytes` accepts binary K/M/G/T suffixes; `Mebibytes` uses MiB for bare numbers.
Integer range validators use the displayed unit in the option name. Enum values
and additional subsystem checks remain case/format dependent as documented.
`Removed` entries reject use and are retained here to explain the diagnostic.
See [interface stability](configuration.md#interface-stability).

| Option | Environment | Startup validator | Option aliases | CLI |
| --- | --- | --- | --- | --- |
"""
    for name, env, kind, aliases, cli in sorted(entries):
        kind = " ".join(kind.replace("OptionKind::", "").split())
        fixed = {
            "Bool": "ON/OFF",
            "U16": "Integer 0..65535",
            "U32": "Integer 0..4294967295",
            "U64": "Unsigned 64-bit integer",
            "Bytes": "Byte size",
            "Mebibytes": "MiB (bare number)",
            "IpAddr": "IPv4 or IPv6 address",
            "NonEmpty": "Nonempty string",
            "String": "String",
        }
        bounded = re.fullmatch(r"(U64Range|BytesRange)\(([^,]+), ([^)]+)\)", kind)
        if bounded:
            kind = (
                ("Bytes " if bounded[1] == "BytesRange" else "Integer ")
                + bounded[2].replace("_", "")
                + ".."
                + bounded[3].replace("_", "")
            )
        elif kind.startswith("Enum("):
            kind = "One of: " + ", ".join(re.findall(r'"([^"]+)"', kind))
        elif kind.startswith("Removed("):
            kind = "Rejected: " + re.search(r'"([^"]+)"', kind)[1]
        else:
            kind = fixed.get(kind, kind)
        kind = kind.replace("|", "\\|")
        text += f"| `{name}` | `{env}` | `{kind}` | {aliases or '—'} | {'Yes' if cli else 'No'} |\n"
    yield ROOT / "docs/configuration-registry.md", text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, text in generated():
        if args.check:
            if not path.exists() or path.read_text() != text:
                parser.exit(1, f"{path.relative_to(ROOT)} is stale\n")
        else:
            path.write_text(text)
    print("Public error and startup-option references are current.")


if __name__ == "__main__":
    main()
