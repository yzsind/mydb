#!/usr/bin/env python3
"""Generate the MySQL 8.0.46 Community Performance Schema catalog."""

from __future__ import annotations

import argparse
import collections
import json
import pathlib
import re
import subprocess
import tempfile

from _mysql80_metadata import system_column, render_column_metadata_lookup


ROOT = pathlib.Path(__file__).resolve().parents[1]
FIXTURE = ROOT / "docs/fixtures/mysql80-performance-schema-8.0.46.json"
OUTPUT = ROOT / "src/engine/performance_schema_mysql80_generated.rs"


def rust_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def ident(value: str) -> str:
    value = re.sub(r"[^A-Za-z0-9]+", "_", value).strip("_").upper()
    if not value or value[0].isdigit():
        value = "PFS_" + value
    return value


def opt_number(value: object) -> str:
    return "None" if value is None else f"Some({int(str(value))})"


def opt_string(value: object) -> str:
    return "None" if value is None else f"Some({rust_string(str(value))})"


def result_type(column: dict[str, object]) -> str:
    data_type = str(column["data_type"])
    if data_type == "tinyint":
        return "ColumnType::Tiny"
    if data_type == "smallint":
        return "ColumnType::Short"
    if data_type == "mediumint":
        return "ColumnType::MediumInt"
    if data_type == "int":
        return "ColumnType::Long"
    if data_type == "bigint":
        return "ColumnType::LongLong"
    if data_type == "float":
        return "ColumnType::Float"
    if data_type == "double":
        return "ColumnType::Double"
    if data_type == "decimal":
        precision = int(str(column["numeric_precision"] or 65))
        scale = int(str(column["numeric_scale"] or 0))
        return f"ColumnType::Decimal {{ precision: {precision}, scale: {scale} }}"
    if data_type == "date":
        return "ColumnType::Date"
    if data_type == "time":
        return "ColumnType::Time"
    if data_type == "datetime":
        return "ColumnType::DateTime"
    if data_type == "timestamp":
        return "ColumnType::Timestamp"
    if data_type == "json":
        return "ColumnType::Json"
    if data_type in {"blob", "longblob", "text", "mediumtext", "longtext"}:
        return "ColumnType::Blob"
    if data_type in {"binary", "varbinary", "char", "varchar", "enum", "set"}:
        return "ColumnType::VarString"
    raise SystemExit(f"unsupported Performance Schema type {data_type!r}")


def render(payload: dict[str, object]) -> str:
    tables = list(payload["tables"])
    columns_by_table: dict[str, list[dict[str, object]]] = collections.defaultdict(list)
    for column in payload["columns"]:
        columns_by_table[str(column["table_name"])].append(column)
    indexes_by_table: dict[str, list[dict[str, object]]] = collections.defaultdict(list)
    for index in payload["indexes"]:
        indexes_by_table[str(index["table_name"])].append(index)

    out = [
        "// @generated by scripts/generate_mysql80_performance_schema_rust.py",
        "// Oracle MySQL 8.0.46 Community Performance Schema contract.",
        "",
        "use crate::engine::information_schema::{SystemColumn, SystemTableDef, SystemTableIndex};",
        "use crate::engine::information_schema_mysql80_character_metadata::ColumnMetadata;",
        "use crate::types::ColumnType;",
        "",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub(crate) struct TableMetadata {",
        "    pub version: Option<u64>,",
        "    pub row_format: Option<&'static str>,",
        "    pub table_rows: Option<u64>,",
        "    pub avg_row_length: Option<u64>,",
        "    pub data_length: Option<u64>,",
        "    pub max_data_length: Option<u64>,",
        "    pub index_length: Option<u64>,",
        "    pub data_free: Option<u64>,",
        "    pub auto_increment: Option<u64>,",
        "    pub table_collation: Option<&'static str>,",
        "    pub checksum: Option<u64>,",
        "    pub create_options: &'static str,",
        "    pub table_comment: &'static str,",
        "}",
        "",
        "#[derive(Clone, Copy, Debug)]",
        "pub(crate) struct SetupInstrumentDefault {",
        "    pub name: &'static str,",
        "    pub enabled: bool,",
        "    pub timed: Option<bool>,",
        "    pub properties: &'static str,",
        "    pub flags: Option<&'static str>,",
        "    pub volatility: i32,",
        "    pub documentation: Option<&'static str>,",
        "}",
        "",
        "#[derive(Clone, Copy, Debug)]",
        "pub(crate) struct SetupThreadDefault {",
        "    pub name: &'static str,",
        "    pub enabled: bool,",
        "    pub history: bool,",
        "    pub properties: &'static str,",
        "    pub volatility: i32,",
        "    pub documentation: Option<&'static str>,",
        "}",
        "",
    ]

    for table in tables:
        name = str(table["table_name"])
        prefix = ident(name)
        out.append(f"const {prefix}_COLUMNS: &[SystemColumn] = &[")
        for column in columns_by_table[name]:
            out.extend(system_column(column, result_type(column)))
        out.append("];")

        grouped: dict[str, list[dict[str, object]]] = collections.OrderedDict()
        for index in indexes_by_table[name]:
            grouped.setdefault(str(index["index_name"]), []).append(index)
        for index_name, parts in grouped.items():
            iprefix = f"{prefix}_{ident(index_name)}"
            cols = ", ".join(rust_string(str(part["column_name"])) for part in parts)
            out.append(f"const {iprefix}_COLUMN_NAMES: &[&str] = &[{cols}];")
        out.append(f"const {prefix}_INDEXES: &[SystemTableIndex] = &[")
        for index_name, parts in grouped.items():
            first = parts[0]
            iprefix = f"{prefix}_{ident(index_name)}"
            out.extend(
                [
                    "    SystemTableIndex {",
                    f"        name: {rust_string(index_name)},",
                    f"        unique: {str(str(first['non_unique']) == '0').lower()},",
                    f"        columns: {iprefix}_COLUMN_NAMES,",
                    f"        index_type: {rust_string(str(first['index_type']))},",
                    f"        visible: {str(first['is_visible'] == 'YES').lower()},",
                    "    },",
                ]
            )
        out.append("];")
        out.append("")

    out.append("pub(crate) const COMMUNITY_DEFS: &[SystemTableDef] = &[")
    creates = payload["create_sql"]
    for table in tables:
        name = str(table["table_name"])
        prefix = ident(name)
        out.extend(
            [
                "    SystemTableDef {",
                '        schema: "performance_schema",',
                f"        name: {rust_string(name.lower())},",
                '        table_type: "BASE TABLE",',
                f"        columns: {prefix}_COLUMNS,",
                '        engine: "PERFORMANCE_SCHEMA",',
                f"        indexes: {prefix}_INDEXES,",
                f"        create_sql: Some({rust_string(str(creates[name]))}),",
                "        hidden: false,",
                "    },",
            ]
        )
    out.extend(["];;".replace(";;", ";"), ""])

    out.append("pub(crate) const ERROR_CATALOG: &[(Option<u16>, Option<&str>, Option<&str>)] = &[")
    for row in payload["error_catalog"]:
        out.append(
            f"    ({opt_number(row['error_number'])}, {opt_string(row['error_name'])}, {opt_string(row['sql_state'])}),"
        )
    out.extend(["];", ""])

    out.append("pub(crate) const SYSTEM_VARIABLE_DEFAULTS: &[(&str, &str)] = &[")
    for row in payload["system_variables"]:
        out.append(
            f"    ({rust_string(str(row['name']))}, {rust_string(str(row['value']))}),"
        )
    out.extend(["];", ""])

    out.extend(render_column_metadata_lookup(
        (str(table["table_name"]).lower(), column, column["column_default"])
        for table in tables
        for column in columns_by_table[str(table["table_name"])]
    ))

    out.append("pub(crate) fn instrument_index(name: &str) -> Option<usize> {")
    out.append("    match name {")
    for index, row in enumerate(payload["setup_defaults"]["setup_instruments"]):
        out.append(f"        {rust_string(str(row['NAME']))} => Some({index}),")
    out.extend(["        _ => None,", "    }", "}", ""])

    out.append("pub(crate) fn thread_class_index(name: &str) -> Option<usize> {")
    out.append("    match name {")
    for index, row in enumerate(payload["setup_defaults"]["setup_threads"]):
        out.append(f"        {rust_string(str(row['NAME']))} => Some({index}),")
    out.extend(["        _ => None,", "    }", "}", ""])

    out.append("pub(crate) fn table_metadata(table: &str) -> Option<TableMetadata> {")
    out.append("    match table {")
    for table in tables:
        name = str(table["table_name"])
        out.extend(
            [
                f"        {rust_string(name.lower())} => Some(TableMetadata {{",
                f"            version: {opt_number(table['version'])},",
                f"            row_format: {opt_string(table['row_format'])},",
                f"            table_rows: {opt_number(table['table_rows'])},",
                f"            avg_row_length: {opt_number(table['avg_row_length'])},",
                f"            data_length: {opt_number(table['data_length'])},",
                f"            max_data_length: {opt_number(table['max_data_length'])},",
                f"            index_length: {opt_number(table['index_length'])},",
                f"            data_free: {opt_number(table['data_free'])},",
                f"            auto_increment: {opt_number(table['auto_increment'])},",
                f"            table_collation: {opt_string(table['table_collation'])},",
                f"            checksum: {opt_number(table['checksum'])},",
                f"            create_options: {rust_string(str(table['create_options'] or ''))},",
                f"            table_comment: {rust_string(str(table['table_comment'] or ''))},",
                "        }),",
            ]
        )
    out.extend(["        _ => None,", "    }", "}", ""])

    out.append("pub(crate) const SETUP_CONSUMERS_DEFAULTS: &[(&str, bool)] = &[")
    for row in payload["setup_defaults"]["setup_consumers"]:
        out.append(
            f"    ({rust_string(str(row['NAME']))}, {str(row['ENABLED'] == 'YES').lower()}),"
        )
    out.extend(["];", ""])

    out.append("pub(crate) const SETUP_INSTRUMENT_DEFAULTS: &[SetupInstrumentDefault] = &[")
    for row in payload["setup_defaults"]["setup_instruments"]:
        out.extend(
            [
                "    SetupInstrumentDefault {",
                f"        name: {rust_string(str(row['NAME']))},",
                f"        enabled: {str(row['ENABLED'] == 'YES').lower()},",
                f"        timed: {'None' if row['TIMED'] is None else 'Some(' + str(row['TIMED'] == 'YES').lower() + ')'},",
                f"        properties: {rust_string(str(row['PROPERTIES'] or ''))},",
                f"        flags: {opt_string(row['FLAGS'])},",
                f"        volatility: {int(str(row['VOLATILITY']))},",
                f"        documentation: {opt_string(row['DOCUMENTATION'])},",
                "    },",
            ]
        )
    out.extend(["];", ""])

    out.append("pub(crate) const SETUP_THREAD_DEFAULTS: &[SetupThreadDefault] = &[")
    for row in payload["setup_defaults"]["setup_threads"]:
        out.extend(
            [
                "    SetupThreadDefault {",
                f"        name: {rust_string(str(row['NAME']))},",
                f"        enabled: {str(row['ENABLED'] == 'YES').lower()},",
                f"        history: {str(row['HISTORY'] == 'YES').lower()},",
                f"        properties: {rust_string(str(row['PROPERTIES'] or ''))},",
                f"        volatility: {int(str(row['VOLATILITY']))},",
                f"        documentation: {opt_string(row['DOCUMENTATION'])},",
                "    },",
            ]
        )
    out.extend(["];", ""])

    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    payload = json.loads(FIXTURE.read_text(encoding="utf-8"))
    if payload.get("oracle_mysql_version") != "8.0.46" or payload.get("table_count") != 111:
        raise SystemExit("fixture is not the fixed MySQL 8.0.46 Community contract")
    generated = render(payload)
    with tempfile.NamedTemporaryFile("w", suffix=".rs", encoding="utf-8", delete=False) as tmp:
        tmp.write(generated)
        temporary = pathlib.Path(tmp.name)
    try:
        subprocess.run(
            ["rustfmt", "--edition", "2021", str(temporary)],
            cwd=ROOT,
            check=True,
        )
        generated = temporary.read_text(encoding="utf-8")
    finally:
        temporary.unlink(missing_ok=True)
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != generated:
            raise SystemExit(f"generated Performance Schema catalog is stale: {OUTPUT}")
        return 0
    OUTPUT.write_text(generated, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
