#!/usr/bin/env python3
"""Summarize the PostgreSQL TPC-DS reference run into a Markdown report.

Reads the run artifacts produced by run_pg_expected.sh:
  <results>/golden_status.csv   query_num,status,rows,elapsed_ms   (parallel off)
  <results>/pg_query_times.csv  query_num,elapsed_ms               (warm, parallel=2)
and the generated expected/sf-<SF>/qNN.tsv files, and writes
  scripts/tpcds/expected/sf-<SF>/REPORT.md
"""
from __future__ import annotations

import csv
import statistics
import sys
from pathlib import Path

SUITE = Path(__file__).resolve().parent.parent
RESULTS = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("/tmp/mydb/tpcds-pg-results")
SF = sys.argv[2] if len(sys.argv) > 2 else "1"
OUT_DIR = SUITE / "expected" / f"sf-{SF}"


def read_csv(path: Path) -> dict[int, dict[str, str]]:
    if not path.is_file():
        return {}
    with path.open() as f:
        return {int(r["query_num"]): r for r in csv.DictReader(f)}


def main() -> int:
    golden = read_csv(RESULTS / "golden_status.csv")
    perf = read_csv(RESULTS / "pg_query_times.csv")

    rows = []
    perf_vals = []
    ok = fail = 0
    for q in range(1, 100):
        g = golden.get(q, {})
        status = g.get("status", "missing")
        nrows = g.get("rows", "")
        tsv = OUT_DIR / f"q{q:02d}.tsv"
        ptime = perf.get(q, {}).get("elapsed_ms", "")
        try:
            ptime_i = int(ptime)
        except ValueError:
            ptime_i = -1
        if status == "ok":
            ok += 1
            if ptime_i >= 0:
                perf_vals.append((q, ptime_i))
        elif status != "missing":
            fail += 1
        rows.append((q, status, nrows, ptime_i, tsv.is_file()))

    lines = []
    lines.append(f"# TPC-DS SF={SF} — PostgreSQL reference run")
    lines.append("")
    lines.append("Generated by `scripts/tpcds/pg/run_pg_expected.sh` against the local "
                 "PostgreSQL 18 instance. The `qNN.tsv` files in this directory are the "
                 "canonical expected result sets (tab-separated, no header, NULL = literal "
                 "`NULL`) consumed by `scripts/tpcds_check_results.py`.")
    lines.append("")
    lines.append("## Summary")
    lines.append("")
    lines.append(f"- Queries executed OK (golden pass): **{ok}/99**" + (f", failed: {fail}" if fail else ""))
    if perf_vals:
        times = [t for _, t in perf_vals]
        total = sum(times)
        slow = sorted(perf_vals, key=lambda x: -x[1])[:10]
        lines.append(f"- Performance pass (warm, `work_mem=64MB`, `max_parallel_workers_per_gather=2`):")
        lines.append(f"  - total **{total/1000:.1f} s**, mean **{statistics.mean(times):.0f} ms**, "
                     f"median **{statistics.median(times):.0f} ms**, max **{max(times)} ms**")
        lines.append(f"  - 10 slowest: " + ", ".join(f"q{q:02d}={t} ms" for q, t in slow))
    lines.append("")
    lines.append("## Config")
    lines.append("")
    lines.append("- golden pass: `max_parallel_workers_per_gather=0` (deterministic, reproducible output), "
                 "`work_mem=256MB`, `jit=off`")
    lines.append("- perf pass: `max_parallel_workers_per_gather=2`, `work_mem=64MB`, "
                 "`effective_cache_size=2GB`, `jit=off`, warm cache "
                 "(matches the documented mydb-comparison baseline)")
    lines.append("")
    lines.append("## Per-query")
    lines.append("")
    lines.append("| Query | golden status | rows | perf (ms, parallel=2 warm) |")
    lines.append("|---|---|---:|---:|")
    heavy = []   # golden ok but not measured at parallel=2 (skipped as too slow)
    for q, status, nrows, ptime_i, has_tsv in rows:
        pt = "" if ptime_i < 0 else str(ptime_i)
        mark = status if status == "ok" else f"**{status}**"
        lines.append(f"| q{q:02d} | {mark} | {nrows} | {pt} |")
        if status == "ok" and ptime_i < 0:
            heavy.append((q, golden.get(q, {}).get("elapsed_ms", "")))
    lines.append("")
    lines.append("## Notes")
    lines.append("")
    if heavy:
        lines.append("- Excluded from the `parallel=2` perf pass (pathologically slow on PG — the "
                     "`year_total` self-join family); their golden result is captured, and they "
                     "completed at `parallel=4`/`work_mem=1GB` in: "
                     + ", ".join(f"q{q:02d}≈{int(ms)//1000 if ms.isdigit() else ms} s"
                                 for q, ms in heavy) + ".")
    lines.append("- Row order is compared **exactly**. PG-vs-mydb semantic differences (NULL "
                 "ordering in `ROLLUP`, tie-breaking, integer division) are expected on some "
                 "queries — see `../README.md` before treating a mismatch as a mydb bug.")
    lines.append("")

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "REPORT.md").write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT_DIR/'REPORT.md'}  (ok={ok} fail={fail} perf_measured={len(perf_vals)})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
