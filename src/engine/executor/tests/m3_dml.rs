/// M3.B1 — INSERT…SELECT now streams the SELECT side row chunks
/// through the storage layer instead of materialising the whole
/// result. The user-visible contract — `affected_rows`, ordering
/// of generated AUTO_INCREMENT ids, the per-statement
/// `LAST_INSERT_ID()` — must match the legacy path exactly. This
/// test seeds a source table with more rows than one test chunk
/// (`INSERT_SELECT_CHUNK_ROWS = 64` under `cfg(test)`) so the streaming loop
/// runs multiple chunks under the hood, then verifies the
/// destination row count, ordering and final values.
#[test]
fn insert_select_streams_in_chunks_and_preserves_row_count() {
    let dir = tempfile::tempdir().unwrap();
    let engine = open_test_engine(dir.path());
    let mut session = SessionContext::default();
    engine
        .execute_with_session(&mut session, "CREATE TABLE src (id INT PRIMARY KEY, v INT)")
        .unwrap();
    engine
        .execute_with_session(&mut session, "CREATE TABLE dst (id INT PRIMARY KEY, v INT)")
        .unwrap();
    // Build a VALUES list straddling more than one test chunk to force
    // the streaming loop to iterate without turning this into a throughput
    // benchmark.
    let n = 160u32;
    let mut sql = String::from("INSERT INTO src VALUES ");
    for i in 0..n {
        if i > 0 {
            sql.push(',');
        }
        sql.push_str(&format!("({0}, {0})", i + 1));
    }
    engine.execute_with_session(&mut session, &sql).unwrap();
    let baseline = engine.database().dml_stats_snapshot().insert_rows;

    let response = engine
        .execute_with_session(&mut session, "INSERT INTO dst SELECT id, v FROM src")
        .unwrap();
    assert_eq!(
        response,
        QueryResponse::OkAffected {
            affected_rows: n as u64
        }
    );
    let after = engine.database().dml_stats_snapshot().insert_rows;
    assert_eq!(after - baseline, n as u64);

    // Spot-check head and tail of the destination to make sure the
    // chunked streaming preserved order.
    let head = rows(
        engine
            .execute_with_session(&mut session, "SELECT id, v FROM dst ORDER BY id LIMIT 3")
            .unwrap(),
    );
    assert_eq!(
        head,
        vec![
            vec![Value::Int(1), Value::Int(1)],
            vec![Value::Int(2), Value::Int(2)],
            vec![Value::Int(3), Value::Int(3)],
        ]
    );
    let tail = rows(
        engine
            .execute_with_session(
                &mut session,
                "SELECT id, v FROM dst ORDER BY id DESC LIMIT 1",
            )
            .unwrap(),
    );
    assert_eq!(tail, vec![vec![Value::Int(n as i64), Value::Int(n as i64)]]);
}

/// M3.B1 — Halloween hazard: `INSERT INTO t SELECT * FROM t` must
/// not feed its own writes back through the SELECT. The streaming
/// implementation pins the SELECT's snapshot_scn at the start of
/// the INSERT; new rows the INSERT writes carry a later
/// last_txn_id and are filtered by MVCC visibility.
#[test]
fn insert_select_into_same_table_is_halloween_safe() {
    let dir = tempfile::tempdir().unwrap();
    let engine = open_test_engine(dir.path());
    let mut session = SessionContext::default();
    engine
        .execute_with_session(&mut session, "CREATE TABLE t (id INT PRIMARY KEY, v INT)")
        .unwrap();
    engine
        .execute_with_session(&mut session, "INSERT INTO t VALUES (1, 1), (2, 2), (3, 3)")
        .unwrap();
    engine
        .execute_with_session(&mut session, "INSERT INTO t SELECT id + 100, v FROM t")
        .unwrap();
    // Only the original three rows feed into the SELECT; we expect
    // 6 rows total (3 originals + 3 generated by adding 100), not
    // a runaway 6/12/24/… stream as would happen if SELECT could
    // observe its own INSERTs.
    let count = rows(
        engine
            .execute_with_session(&mut session, "SELECT COUNT(*) FROM t")
            .unwrap(),
    );
    assert_eq!(count, vec![vec![Value::Int(6)]]);
}

/// REPLACE…SELECT from the same table is Halloween-safe too: the SELECT
/// side runs under the pinned snapshot, so it reads only the pre-statement
/// rows even though each REPLACE deletes the conflicting original and
/// inserts a fresh row. mydb deliberately supports this (MySQL rejects it
/// with 1093 — an intentional superset, same as INSERT…SELECT self-ref).
#[test]
fn replace_select_into_same_table_is_halloween_safe() {
    let dir = tempfile::tempdir().unwrap();
    let engine = open_test_engine(dir.path());
    let mut session = SessionContext::default();
    engine
        .execute_with_session(&mut session, "CREATE TABLE t (id INT PRIMARY KEY, v INT)")
        .unwrap();
    engine
        .execute_with_session(&mut session, "INSERT INTO t VALUES (1, 1), (2, 2), (3, 3)")
        .unwrap();
    // Each row conflicts on its own PK → delete original, insert v+100.
    engine
        .execute_with_session(&mut session, "REPLACE INTO t SELECT id, v + 100 FROM t")
        .unwrap();
    // Exactly the three originals are replaced in place — no runaway, no dupes.
    let out = rows(
        engine
            .execute_with_session(&mut session, "SELECT id, v FROM t ORDER BY id")
            .unwrap(),
    );
    assert_eq!(
        out,
        vec![
            vec![Value::Int(1), Value::Int(101)],
            vec![Value::Int(2), Value::Int(102)],
            vec![Value::Int(3), Value::Int(103)],
        ]
    );
}

/// M3.B2 — Same-transaction repeated INSERTs should pull from one
/// reservation rather than racing on the global counter for every
/// row. The DML reservation map shrinks back to empty on COMMIT;
/// nothing visible is left behind besides the values themselves.
#[test]
fn autoinc_reservation_serves_repeated_inserts_in_one_txn() {
    let dir = tempfile::tempdir().unwrap();
    let engine = open_test_engine(dir.path());
    let mut session = SessionContext::default();
    engine
        .execute_with_session(
            &mut session,
            "CREATE TABLE t (id INT NOT NULL AUTO_INCREMENT PRIMARY KEY, v INT)",
        )
        .unwrap();
    engine.execute_with_session(&mut session, "BEGIN").unwrap();
    for v in 0..32 {
        engine
            .execute_with_session(&mut session, &format!("INSERT INTO t(v) VALUES ({})", v))
            .unwrap();
    }
    engine.execute_with_session(&mut session, "COMMIT").unwrap();
    let stored = rows(
        engine
            .execute_with_session(&mut session, "SELECT id FROM t ORDER BY id")
            .unwrap(),
    );
    // 32 monotonically ascending ids starting at 1. The exact
    // values can include gaps as the reservation grows past the
    // tail of the transaction, but every id must be unique and
    // ascending and at least 1.
    assert_eq!(stored.len(), 32);
    let mut prev = 0i64;
    for row in stored {
        let id = match row[0] {
            Value::Int(v) => v,
            _ => panic!("expected Int(id)"),
        };
        assert!(id > prev, "ids must be strictly ascending");
        prev = id;
    }
}

/// M3.B2 — Autocommit single-row INSERT must still hand out
/// consecutive ids with no gap (mode-1 semantics). The reservation
/// path falls back to size=need when no prior reservation exists
/// for the txn, so the autocommit sequence is exactly the same as
/// the legacy path.
#[test]
fn autoinc_autocommit_inserts_have_no_gaps() {
    let dir = tempfile::tempdir().unwrap();
    let engine = open_test_engine(dir.path());
    engine
        .execute("CREATE TABLE t (id INT NOT NULL AUTO_INCREMENT PRIMARY KEY, v INT)")
        .unwrap();
    for v in 0..5 {
        engine
            .execute(&format!("INSERT INTO t(v) VALUES ({})", v))
            .unwrap();
    }
    let stored = rows(engine.execute("SELECT id FROM t ORDER BY id").unwrap());
    assert_eq!(
        stored,
        vec![
            vec![Value::Int(1)],
            vec![Value::Int(2)],
            vec![Value::Int(3)],
            vec![Value::Int(4)],
            vec![Value::Int(5)],
        ]
    );
}

/// M3.B5 — UPDATE … ORDER BY id DESC LIMIT 3 must touch exactly
/// the three largest ids even with no usable index on the sort
/// column (DESC currently disables the index fast path; without
/// the TopN heap the executor would materialise every candidate
/// row + WHERE-filter + sort O(N log N) before truncating).
#[test]
fn topn_update_descending_limit_touches_only_top_rows() {
    let dir = tempfile::tempdir().unwrap();
    let engine = open_test_engine(dir.path());
    engine
        .execute("CREATE TABLE t (id INT PRIMARY KEY, v INT)")
        .unwrap();
    let mut sql = String::from("INSERT INTO t VALUES ");
    for i in 0..200u32 {
        if i > 0 {
            sql.push(',');
        }
        sql.push_str(&format!("({0}, {0})", i + 1));
    }
    engine.execute(&sql).unwrap();
    let response = engine
        .execute("UPDATE t SET v = -1 WHERE v > 0 ORDER BY id DESC LIMIT 3")
        .unwrap();
    assert_eq!(response, QueryResponse::OkAffected { affected_rows: 3 });

    let bumped = rows(
        engine
            .execute("SELECT id, v FROM t WHERE v = -1 ORDER BY id")
            .unwrap(),
    );
    assert_eq!(
        bumped,
        vec![
            vec![Value::Int(198), Value::Int(-1)],
            vec![Value::Int(199), Value::Int(-1)],
            vec![Value::Int(200), Value::Int(-1)],
        ]
    );
}

/// M3.B5 — DELETE … ORDER BY v LIMIT k under the TopN heap path.
/// Uses an unindexed sort column so the fast index path is not
/// eligible; verifies the smallest K rows are removed and the
/// rest survive unchanged.
#[test]
fn topn_delete_ascending_limit_removes_only_min_rows() {
    let dir = tempfile::tempdir().unwrap();
    let engine = open_test_engine(dir.path());
    engine
        .execute("CREATE TABLE t (id INT PRIMARY KEY, v INT)")
        .unwrap();
    // Insert in reverse value order so the smallest values are
    // scattered through the heap and the sort matters.
    let mut sql = String::from("INSERT INTO t VALUES ");
    for i in 0..50u32 {
        if i > 0 {
            sql.push(',');
        }
        sql.push_str(&format!("({}, {})", i + 1, 100 - i));
    }
    engine.execute(&sql).unwrap();
    let response = engine.execute("DELETE FROM t ORDER BY v LIMIT 4").unwrap();
    assert_eq!(response, QueryResponse::OkAffected { affected_rows: 4 });
    // Smallest four v's were 51, 52, 53, 54 — they belong to
    // ids 50, 49, 48, 47 (the inverted seed).
    let remaining = rows(
        engine
            .execute("SELECT v FROM t WHERE v < 60 ORDER BY v")
            .unwrap(),
    );
    assert_eq!(
        remaining,
        vec![
            vec![Value::Int(55)],
            vec![Value::Int(56)],
            vec![Value::Int(57)],
            vec![Value::Int(58)],
            vec![Value::Int(59)],
        ]
    );
}

/// M3.B9 — Bulk INSERT that crosses the merge-join threshold
/// (1024 rows) and reports a single conflict via the merge-join
/// path. Without the merge optimisation we still detect the
/// conflict; the test makes sure the merge path produces the
/// identical 1062 error and rolls back cleanly.
#[test]
fn bulk_insert_unique_conflict_detected_by_merge_join() {
    let dir = tempfile::tempdir().unwrap();
    let engine = open_test_engine(dir.path());
    engine
        .execute("CREATE TABLE t (id INT PRIMARY KEY)")
        .unwrap();
    // Seed an existing row that will collide with one of the new
    // batch's keys (id = 500).
    engine.execute("INSERT INTO t VALUES (500)").unwrap();

    // Build a large batch covering [1, 2000] excluding 500 of
    // course wait — we deliberately include 500 to force the
    // conflict the merge path is supposed to find.
    let mut sql = String::from("INSERT INTO t VALUES ");
    for i in 0..2000u32 {
        if i > 0 {
            sql.push(',');
        }
        sql.push_str(&format!("({})", i + 1));
    }
    let err = engine.execute(&sql).expect_err("expected 1062 duplicate");
    assert_eq!(err.code(), 1062);
    // Only the seed row survived; the batch was rolled back.
    let count = rows(engine.execute("SELECT COUNT(*) FROM t").unwrap());
    assert_eq!(count, vec![vec![Value::Int(1)]]);
}

/// M3.B9 — Bulk INSERT below the merge threshold (256 rows) must
/// still pass through the legacy row-by-row UNIQUE check. The
/// guarantee here is purely behavioural: the same conflict the
/// merge path catches is also caught by the legacy path.
#[test]
fn small_insert_unique_conflict_detected_by_legacy_lookup() {
    let dir = tempfile::tempdir().unwrap();
    let engine = open_test_engine(dir.path());
    engine
        .execute("CREATE TABLE t (id INT PRIMARY KEY)")
        .unwrap();
    engine.execute("INSERT INTO t VALUES (10)").unwrap();

    let mut sql = String::from("INSERT INTO t VALUES ");
    for i in 0..50u32 {
        if i > 0 {
            sql.push(',');
        }
        // The first 50 rows include id=10, so the loop hits a
        // collision well before the merge threshold trips.
        sql.push_str(&format!("({})", i + 1));
    }
    let err = engine.execute(&sql).expect_err("expected 1062 duplicate");
    assert_eq!(err.code(), 1062);
    let count = rows(engine.execute("SELECT COUNT(*) FROM t").unwrap());
    assert_eq!(count, vec![vec![Value::Int(1)]]);
}
