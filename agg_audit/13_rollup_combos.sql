# ROLLUP 组合场景: JOIN / 子查询 / UNION / 视图 / 窗口
SELECT t1.a, t2.v, COUNT(*) FROM t1 JOIN t2 ON t1.a = t2.k GROUP BY t1.a, t2.v WITH ROLLUP
SELECT t1.a, t2.v, COUNT(*) FROM t1 LEFT JOIN t2 ON t1.a = t2.k GROUP BY t1.a, t2.v WITH ROLLUP
SELECT a, COUNT(*) FROM (SELECT a FROM t1 WHERE a IS NOT NULL) x GROUP BY a WITH ROLLUP
SELECT a, cnt FROM (SELECT a, COUNT(*) cnt FROM t1 GROUP BY a WITH ROLLUP) x
SELECT a, cnt FROM (SELECT a, COUNT(*) cnt FROM t1 GROUP BY a WITH ROLLUP) x WHERE a IS NULL
SELECT g, SUM(c) FROM (SELECT a g, c FROM t1) t GROUP BY g WITH ROLLUP
# UNION 中使用
SELECT a, COUNT(*) FROM t1 GROUP BY a WITH ROLLUP UNION SELECT a, COUNT(*) FROM t1 GROUP BY a
SELECT a, COUNT(*) FROM t1 GROUP BY a UNION ALL SELECT a, COUNT(*) FROM t1 GROUP BY a WITH ROLLUP
# WITH ROLLUP + DISTINCT 修饰聚合
SELECT a, COUNT(DISTINCT b) FROM t1 GROUP BY a WITH ROLLUP
SELECT a, SUM(DISTINCT c) FROM t1 GROUP BY a WITH ROLLUP
SELECT a, AVG(DISTINCT c) FROM t1 GROUP BY a WITH ROLLUP
SELECT a, SUM(DISTINCT d) FROM t1 GROUP BY a WITH ROLLUP
SELECT a, STD(DISTINCT c) FROM t1 GROUP BY a WITH ROLLUP
# 视图
CREATE OR REPLACE VIEW v1 AS SELECT a, b, SUM(c) sc, GROUPING(a) ga, GROUPING(b) gb FROM t1 GROUP BY a, b WITH ROLLUP
SELECT * FROM v1
SELECT a, sc FROM v1 WHERE ga = 1
CREATE OR REPLACE VIEW v2 AS SELECT a, COUNT(*) c FROM t1 GROUP BY a WITH ROLLUP
SELECT * FROM v2 ORDER BY c
# 窗口函数与聚合组合(不在 GROUP BY 内)
SELECT a, SUM(c), SUM(SUM(c)) OVER () FROM t1 GROUP BY a WITH ROLLUP
SELECT a, SUM(c), ROW_NUMBER() OVER (ORDER BY a) FROM t1 GROUP BY a WITH ROLLUP
# HAVING 复杂
SELECT a, b, COUNT(*) FROM t1 GROUP BY a, b WITH ROLLUP HAVING COUNT(*) >= 2
SELECT a, b, SUM(c) FROM t1 GROUP BY a, b WITH ROLLUP HAVING b IS NULL AND a IS NULL
SELECT a, GROUPING(a) FROM t1 GROUP BY a WITH ROLLUP HAVING GROUPING(a) = 0
# 聚合表达式引用分组列
SELECT a, SUM(c)+a FROM t1 GROUP BY a WITH ROLLUP
SELECT a, CONCAT(a, ':', SUM(c)) FROM t1 GROUP BY a WITH ROLLUP
# ROLLUP 大表
SELECT g, h, COUNT(*), SUM(val) FROM tbig GROUP BY g, h WITH ROLLUP ORDER BY g, h, GROUPING(g), GROUPING(h) LIMIT 200
SELECT g, COUNT(DISTINCT h) FROM tbig GROUP BY g WITH ROLLUP ORDER BY g, GROUPING(g)
SELECT g, GROUP_CONCAT(DISTINCT s ORDER BY s) FROM tbig GROUP BY g WITH ROLLUP ORDER BY g, GROUPING(g) LIMIT 100
SELECT s, h, COUNT(*), AVG(val), STD(val) FROM tbig GROUP BY s, h WITH ROLLUP ORDER BY s, h, GROUPING(s), GROUPING(h) LIMIT 200
