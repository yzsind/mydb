# 补充场景: 排序方向/无聚合/COLLATE
SELECT a, b FROM t1 GROUP BY a, b WITH ROLLUP
SELECT a, b, COUNT(*) FROM t1 GROUP BY a ASC, b DESC WITH ROLLUP
SELECT a, b, COUNT(*) FROM t1 GROUP BY b, a WITH ROLLUP
SELECT s, COUNT(*) FROM tstr GROUP BY s COLLATE utf8mb4_bin WITH ROLLUP
SELECT s COLLATE utf8mb4_bin sk, COUNT(*) FROM tstr GROUP BY s COLLATE utf8mb4_bin WITH ROLLUP
SELECT a, COUNT(*) FROM t1 GROUP BY TO_DAYS(f) WITH ROLLUP
SELECT DATE_FORMAT(f, '%Y-%m') m, COUNT(*) FROM t1 GROUP BY DATE_FORMAT(f, '%Y-%m') WITH ROLLUP
SELECT a, COUNT(*) FROM t1 GROUP BY a HAVING SUM(c) > 0 WITH ROLLUP
SELECT a, b FROM t1 GROUP BY a, b WITH ROLLUP LIMIT 5
# 聚合函数中引用其他聚合的表达式(应报错)
SELECT a, SUM(c) + MAX(d) FROM t1 GROUP BY a WITH ROLLUP
SELECT a, SUM(c) * 2 FROM t1 GROUP BY a WITH ROLLUP
# HAVING 聚合与 rollup 行
SELECT a, SUM(c) FROM t1 GROUP BY a WITH ROLLUP HAVING SUM(c) > 100
SELECT a, COUNT(*) FROM t1 GROUP BY a WITH ROLLUP HAVING GROUPING(a) = 1 AND COUNT(*) > 5
# 子查询关联 rollup 输出
SELECT (SELECT MAX(x) FROM (SELECT SUM(c) x FROM t1 GROUP BY a WITH ROLLUP) q) FROM (SELECT 1) z
# UNION 内 rollup 列类型不同
SELECT a, SUM(c) FROM t1 GROUP BY a WITH ROLLUP UNION SELECT s, LENGTH(s) FROM tstr GROUP BY s
