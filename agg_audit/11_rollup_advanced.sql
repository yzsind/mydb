# GROUPING / HAVING / ORDER BY / LIMIT 与 ROLLUP
SELECT a, b, SUM(c), GROUPING(a), GROUPING(b) FROM t1 GROUP BY a, b WITH ROLLUP
SELECT a, b, SUM(c), GROUPING(a, b) FROM t1 GROUP BY a, b WITH ROLLUP
SELECT a, GROUPING(a), SUM(c) FROM t1 GROUP BY a WITH ROLLUP
SELECT a, b, GROUPING(a) FROM t1 GROUP BY a, b WITH ROLLUP
SELECT a, b, SUM(c) FROM t1 GROUP BY a, b WITH ROLLUP HAVING GROUPING(a) = 1
SELECT a, b, SUM(c) FROM t1 GROUP BY a, b WITH ROLLUP HAVING GROUPING(b) = 1 AND a IS NOT NULL
SELECT a, b, SUM(c) FROM t1 GROUP BY a, b WITH ROLLUP HAVING SUM(c) > 30
SELECT a, b, SUM(c) FROM t1 GROUP BY a, b WITH ROLLUP ORDER BY a, b
SELECT a, b, SUM(c) FROM t1 GROUP BY a, b WITH ROLLUP ORDER BY a DESC, b DESC
SELECT a, b, SUM(c) FROM t1 GROUP BY a, b WITH ROLLUP ORDER BY GROUPING(b), a, b
SELECT a, b, SUM(c) FROM t1 GROUP BY a, b WITH ROLLUP ORDER BY 1, 2
SELECT a, b, SUM(c) FROM t1 GROUP BY a, b WITH ROLLUP LIMIT 3
SELECT a, b, SUM(c) FROM t1 GROUP BY a, b WITH ROLLUP ORDER BY GROUPING(b) DESC, a, b LIMIT 4
SELECT a, SUM(c) s FROM t1 GROUP BY a WITH ROLLUP ORDER BY s
SELECT a, SUM(c) s FROM t1 GROUP BY a WITH ROLLUP ORDER BY s DESC
# 表达式 GROUP BY + ROLLUP
SELECT YEAR(f), MONTH(f), COUNT(*) FROM t1 GROUP BY YEAR(f), MONTH(f) WITH ROLLUP
SELECT COALESCE(a, -1) x, b, COUNT(*) FROM t1 GROUP BY COALESCE(a, -1), b WITH ROLLUP
SELECT a*10, COUNT(*) FROM t1 GROUP BY a*10 WITH ROLLUP
SELECT IFNULL(a, 0), b, SUM(c) FROM t1 GROUP BY IFNULL(a,0), b WITH ROLLUP
# 列序号/别名 + ROLLUP
SELECT a, b, SUM(c) FROM t1 GROUP BY 1, 2 WITH ROLLUP
SELECT a AS g1, b AS g2, SUM(c) FROM t1 GROUP BY g1, g2 WITH ROLLUP
SELECT a, b, SUM(c) FROM t1 GROUP BY 1 WITH ROLLUP
# 常量/无意义组合
SELECT 'lit', a, COUNT(*) FROM t1 GROUP BY 'lit', a WITH ROLLUP
SELECT a, COUNT(*) FROM t1 WHERE a IS NOT NULL GROUP BY a WITH ROLLUP
SELECT a, COUNT(*) FROM t1 WHERE 1=0 GROUP BY a WITH ROLLUP
# DISTINCT 查询 + ROLLUP
SELECT DISTINCT a, GROUPING(a) FROM t1 GROUP BY a WITH ROLLUP
# HAVING 引用别名/聚合
SELECT a, SUM(c) AS s FROM t1 GROUP BY a WITH ROLLUP HAVING s > 10
SELECT a, SUM(c) FROM t1 GROUP BY a WITH ROLLUP HAVING a IS NULL
SELECT a, SUM(c) FROM t1 GROUP BY a WITH ROLLUP HAVING SUM(c) IS NULL
