SELECT SUM(de), AVG(de), MIN(de), MAX(de) FROM tnum
SELECT SUM(du), AVG(du) FROM tnum
SELECT AVG(ti), AVG(si), AVG(bl) FROM tnum
SELECT SUM(fl), AVG(fl) FROM tnum
SELECT SUM(dl), AVG(dl), STD(dl) FROM tnum
SELECT SUM(bt), MAX(bt), MIN(bt) FROM tnum
