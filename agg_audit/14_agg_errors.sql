# 错误与合法性(双方都应报同样类别错误)
SELECT a, SUM(a) FROM t1 GROUP BY a WITH ROLLUP
SELECT c, COUNT(*) FROM t1 GROUP BY a WITH ROLLUP
SELECT SUM(a) FROM t1 WHERE SUM(a) > 1
SELECT SUM(SUM(a)) FROM t1
SELECT SUM(a) FROM t1 GROUP BY a WITH ROLLUP GROUP BY b
SELECT SUM(c) FROM t1 GROUP BY b WITH ROLLUP ORDER BY SUM(c) DESC, 3
SELECT GROUPING(a) FROM t1
SELECT GROUPING(c), COUNT(*) FROM t1 GROUP BY a, c WITH ROLLUP
SELECT a, GROUPING(a) FROM t1 GROUP BY a, b WITH ROLLUP
SELECT COUNT(a, b) FROM t1
SELECT COUNT(*) FROM t1 GROUP BY a WITH ROLLUP ORDER BY GROUPING(a)
SELECT * FROM t1 GROUP BY a WITH ROLLUP
SELECT a, b, MAX(c) FROM t1 GROUP BY a WITH ROLLUP
SELECT a, SUM(c) FROM t1 GROUP BY a WITH ROLLUP ORDER BY b
SELECT AVG(x) FROM tagg GROUP BY id WITH ROLLUP ORDER BY AVG(x)
SELECT AVG(x) FROM tagg GROUP BY id WITH ROLLUP ORDER BY x
# prepared 语义: 重复执行同一 rollup
SELECT a, b, SUM(c) FROM t1 GROUP BY a, b WITH ROLLUP
SELECT a, b, SUM(c) FROM t1 GROUP BY a, b WITH ROLLUP
# 大写小写函数名
SELECT COUNT(*), count(*), CoUnT(*) FROM t1 GROUP BY a, b WITH ROLLUP
# 传 NULL 常量分组
SELECT NULL, COUNT(*) FROM t1 GROUP BY NULL WITH ROLLUP
SELECT COUNT(*) FROM t1 GROUP BY a + 0 WITH ROLLUP
# 单列全 NULL 分组
SELECT b, COUNT(*) FROM t1 WHERE b IS NULL GROUP BY b WITH ROLLUP
SELECT b, GROUPING(b) FROM t1 WHERE b IS NULL GROUP BY b WITH ROLLUP
# 超大 scale decimal
SELECT SUM(CAST(c AS DECIMAL(65,30))) FROM t1 GROUP BY a WITH ROLLUP
SELECT AVG(CAST(c AS DECIMAL(65,4))) FROM t1 GROUP BY a WITH ROLLUP
# 除法/除零在聚合参数中
SELECT SUM(1/x), COUNT(*) FROM t1 GROUP BY a WITH ROLLUP
SELECT SUM(c DIV 0), COUNT(*) FROM t1 GROUP BY a WITH ROLLUP
# 聚合溢出到错误
SELECT SUM(c * c * c * c * c * c * c * c * c * c) FROM t1 GROUP BY a WITH ROLLUP
