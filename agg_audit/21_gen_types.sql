# 生成列/时间类型/JSON 键
CREATE TABLE tgen (a INT, b INT AS (a * 2) STORED, c INT AS (a + 1) VIRTUAL, t TIME NULL, y YEAR NULL, j JSON NULL)
INSERT INTO tgen (a, t, y, j) VALUES (1, '10:00:00', 2024, '{"x":1}'), (2, NULL, NULL, NULL), (NULL, '25:00:00', 1999, '[1,2]'), (2, '12:30:30', 2024, '{"x":1}')
SELECT b, COUNT(*), SUM(a) FROM tgen GROUP BY b WITH ROLLUP
SELECT c, COUNT(*) FROM tgen GROUP BY c WITH ROLLUP
SELECT t, COUNT(*) FROM tgen GROUP BY t WITH ROLLUP
SELECT y, COUNT(*), SUM(a) FROM tgen GROUP BY y WITH ROLLUP
SELECT j, COUNT(*), JSON_EXTRACT(j, '$.x') FROM tgen GROUP BY j WITH ROLLUP
SELECT JSON_EXTRACT(j, '$.x') k, COUNT(*) FROM tgen GROUP BY k WITH ROLLUP
# TIME/YEAR 聚合
SELECT SUM(t), MIN(t), MAX(t), AVG(t) FROM tgen
SELECT SUM(y), MIN(y), MAX(y), AVG(y) FROM tgen
SELECT SUM(a * 1.0) / COUNT(a) FROM tgen GROUP BY b WITH ROLLUP
# ROLLUP + HAVING 别名引用 GROUPING
SELECT y, GROUPING(y) g, COUNT(*) FROM tgen GROUP BY y WITH ROLLUP HAVING g = 0 ORDER BY y
# 聚合作为窗口输入在 ROLLUP 上
SELECT y, SUM(a), RANK() OVER (ORDER BY SUM(a) DESC) FROM tgen GROUP BY y WITH ROLLUP
