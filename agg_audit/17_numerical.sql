# 数值稳定性: 大均值小方差场景
SELECT VARIANCE(x), STD(x) FROM (SELECT 100000000 x UNION ALL SELECT 100000000.01 UNION ALL SELECT 100000000.02) t
SELECT VARIANCE(x) FROM (SELECT 1e8 x UNION ALL SELECT 1e8+0.01 UNION ALL SELECT 1e8+0.02) t
SELECT VARIANCE(x) FROM (SELECT 1000000 x UNION ALL SELECT 1000000 UNION ALL SELECT 1000000 UNION ALL SELECT 1000000.0001) t
SELECT VARIANCE(x) FROM (SELECT 1000000000000 x UNION ALL SELECT 1000000000000.1) t
SELECT STDDEV_SAMP(x) FROM (SELECT 100000000 x UNION ALL SELECT 100000000.01 UNION ALL SELECT 100000000.02) t
SELECT id, VARIANCE(x) FROM (SELECT 1 id, 100000000 x UNION ALL SELECT 1, 100000000.01 UNION ALL SELECT 1, 100000000.02 UNION ALL SELECT 2 id, 1 x UNION ALL SELECT 2, 1.01) t GROUP BY id WITH ROLLUP
SELECT VARIANCE(DISTINCT x) FROM (SELECT 100000000 x UNION ALL SELECT 100000000.01) t
SELECT VARIANCE(x) FROM (SELECT 1e15 x UNION ALL SELECT 1e15+0.5) t
# AVG 精度
SELECT AVG(x) FROM (SELECT 100000000000001.5 x UNION ALL SELECT 100000000000001.7) t
SELECT SUM(x) FROM (SELECT 1e15 x UNION ALL SELECT -1e15 UNION ALL SELECT 1 x) t
# BIT 全 NULL / 部分 NULL
SELECT BIT_AND(x), BIT_OR(x), BIT_XOR(x) FROM (SELECT NULL x UNION ALL SELECT NULL) t
SELECT BIT_AND(x), BIT_OR(x), BIT_XOR(x) FROM (SELECT 1 x UNION ALL SELECT NULL) t
SELECT BIT_AND(x), BIT_OR(x), BIT_XOR(x) FROM (SELECT 5 x UNION ALL SELECT NULL UNION ALL SELECT 3) t
SELECT id, BIT_AND(x) FROM (SELECT 1 id, NULL x UNION ALL SELECT 1, NULL) t GROUP BY id WITH ROLLUP
SELECT id, BIT_OR(x) FROM (SELECT 1 id, NULL x UNION ALL SELECT 1, NULL) t GROUP BY id
# MIN/MAX 全 NULL
SELECT MIN(x), MAX(x) FROM (SELECT NULL x UNION ALL SELECT NULL) t
SELECT GROUP_CONCAT(x) FROM (SELECT NULL x UNION ALL SELECT NULL) t
SELECT SUM(x), AVG(x), COUNT(x) FROM (SELECT NULL x UNION ALL SELECT NULL) t
