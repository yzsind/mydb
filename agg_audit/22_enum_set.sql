# ENUM/SET/ANY_VALUE/排序聚合
CREATE TABLE tenum (id INT, e ENUM('aa','bb','cc') NULL, st SET('x','y','z') NULL)
INSERT INTO tenum VALUES (1,'aa','x,y'),(2,'bb','y'),(3,NULL,NULL),(1,'cc','x,z'),(2,'aa','x'),(3,'bb',NULL)
SELECT e, COUNT(*), MIN(id), MAX(id) FROM tenum GROUP BY e WITH ROLLUP
SELECT st, COUNT(*) FROM tenum GROUP BY st WITH ROLLUP
SELECT SUM(e), AVG(id) FROM tenum
SELECT MIN(e), MAX(e) FROM tenum
SELECT id, ANY_VALUE(e), COUNT(*) FROM tenum GROUP BY id
SELECT id, e, COUNT(*) FROM tenum GROUP BY id, e WITH ROLLUP
SELECT SUM(x ORDER BY x) FROM (SELECT 1 x UNION ALL SELECT 2) t
SELECT GROUP_CONCAT(e ORDER BY e DESC SEPARATOR '-') FROM tenum
SELECT id, GROUP_CONCAT(DISTINCT e ORDER BY e DESC) FROM tenum GROUP BY id WITH ROLLUP
