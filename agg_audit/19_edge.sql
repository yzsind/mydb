# 空/极端组合
SELECT a FROM tempty GROUP BY a WITH ROLLUP
SELECT a, COUNT(*) FROM tempty WHERE 1=0 GROUP BY a WITH ROLLUP
SELECT NULL FROM tempty GROUP BY NULL WITH ROLLUP
SELECT 1, COUNT(*) FROM t1 GROUP BY 1 WITH ROLLUP
# CASE 表达式分组
SELECT CASE WHEN a IS NULL THEN 'N' ELSE 'Y' END, COUNT(*) FROM t1 GROUP BY CASE WHEN a IS NULL THEN 'N' ELSE 'Y' END WITH ROLLUP
SELECT CASE a WHEN 1 THEN 'one' WHEN 2 THEN 'two' ELSE 'other' END k, SUM(c) FROM t1 GROUP BY k WITH ROLLUP
# JOIN 星号展开
SELECT * FROM t1 JOIN t2 ON t1.a = t2.k GROUP BY t1.a, t2.v WITH ROLLUP
SELECT t1.*, t2.v FROM t1 JOIN t2 ON t1.a = t2.k GROUP BY t1.a, t2.v WITH ROLLUP
# HAVING 边界
SELECT a, SUM(c) FROM t1 GROUP BY a WITH ROLLUP HAVING c > 0
SELECT a, b, SUM(c) FROM t1 GROUP BY a, b WITH ROLLUP HAVING a = 1
SELECT a, COUNT(*) FROM t1 GROUP BY a WITH ROLLUP HAVING GROUPING(a) IN (0, 1)
SELECT a, GROUPING(a) ga FROM t1 GROUP BY a WITH ROLLUP HAVING ga = 1 ORDER BY a
# ORDER BY 序号引用聚合列
SELECT a, SUM(c) FROM t1 GROUP BY a WITH ROLLUP ORDER BY 2 DESC
SELECT a, SUM(c) FROM t1 GROUP BY a WITH ROLLUP ORDER BY 1
# INSERT-SELECT 从 rollup 结果
CREATE TABLE tins (a INT, s DECIMAL(20,0), gr TINYINT)
INSERT INTO tins SELECT a, SUM(c), GROUPING(a) FROM t1 GROUP BY a WITH ROLLUP
SELECT * FROM tins ORDER BY gr, a
DROP TABLE tins
# GROUPING 非法参数
SELECT a, GROUPING(a+0) FROM t1 GROUP BY a WITH ROLLUP
SELECT a, GROUPING('x') FROM t1 GROUP BY a WITH ROLLUP
SELECT a, GROUPING(b) FROM t1 GROUP BY a WITH ROLLUP
SELECT a, GROUPING(a, b) FROM t1 GROUP BY a, b WITH ROLLUP ORDER BY 3 DESC
# 布尔/零/特殊浮点分组
SELECT bl, COUNT(*) FROM tnum GROUP BY bl WITH ROLLUP
SELECT dl, COUNT(*) FROM tnum WHERE dl = 0 GROUP BY dl WITH ROLLUP
SELECT fl, COUNT(*), SUM(de) FROM tnum GROUP BY fl WITH ROLLUP
# ROLLUP + UNION DISTINCT 去重
SELECT a, COUNT(*) FROM t1 GROUP BY a WITH ROLLUP UNION SELECT a, COUNT(*) FROM t1 GROUP BY a WITH ROLLUP
# 嵌套 rollup 派生表 + 外层聚合
SELECT g, SUM(cnt) FROM (SELECT a g, COUNT(*) cnt FROM t1 GROUP BY a WITH ROLLUP) d GROUP BY g WITH ROLLUP
# EXPLAIN 检查执行路径
EXPLAIN SELECT g, h, COUNT(*) FROM tbig GROUP BY g, h WITH ROLLUP
EXPLAIN SELECT a, SUM(c) FROM t1 GROUP BY a WITH ROLLUP
