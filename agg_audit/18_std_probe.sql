# STD/VARIANCE 精确刻画
SELECT STD(x), VARIANCE(x) FROM (SELECT 10000000000.000001 x UNION ALL SELECT 10000000000.000002) t
SELECT STD(CAST(x AS DOUBLE)), VARIANCE(CAST(x AS DOUBLE)) FROM (SELECT 10000000000.000001 x UNION ALL SELECT 10000000000.000002) t
SELECT STD(x), VARIANCE(x) FROM (SELECT 10000000000000.0000001 x UNION ALL SELECT 10000000000000.0000002) t
SELECT STD(x), VARIANCE(x) FROM (SELECT 10000000000.000001 x UNION ALL SELECT 10000000000.000002 UNION ALL SELECT 10000000000.000003) t
SELECT VARIANCE(x) FROM (SELECT 1e10 x UNION ALL SELECT 1e10+0.000002) t
SELECT VARIANCE(x) FROM (SELECT 10000000000.000002 x UNION ALL SELECT 10000000000.000001) t
SELECT id, STD(x), VARIANCE(x) FROM (SELECT 1 id, 10000000000.000001 x UNION ALL SELECT 1, 10000000000.000002) t GROUP BY id WITH ROLLUP
